import { ENTITIES } from "../records";
import type { Entity } from "../records";
import type { SyncEngine } from "../engine";
import { recordKey } from "../persistence/shared";

// The only prediction exclusions. Client-supplied dates remain exact.
export const EXCLUSIONS = {
  version: "database triggers increment versions, including nested stages",
  newIssueNumber: "the server allocates a workspace issue number on insert",
  timestamps: {
    issues: ["created_at", "updated_at", "deleted_at", "archived_at", "done_at"],
    comments: ["created_at", "edited_at"],
    notifications: ["created_at", "read_at"],
  } satisfies Partial<Record<Entity, string[]>>,
  timestampReason: "the server uses its own clock; compare string presence and nullness",
  newNotifications:
    "notifications generated by a command have server-generated ids and dedup keys; existing notifications still compare",
  activity: "activity is generated on the server with its own ids and clock",
};

export type Snapshot = Map<Entity, Map<string, object>>;
export function snapshot(engine: SyncEngine): Snapshot {
  return new Map(
    ENTITIES.map((entity) => [
      entity,
      new Map(
        engine.store.all(entity).map((row) => [recordKey(entity, row), structuredClone(row)]),
      ),
    ]),
  );
}

function comparable(value: unknown, timestamps: readonly string[], newIssue: boolean): unknown {
  if (Array.isArray(value)) return value.map((item) => comparable(item, [], false));
  if (typeof value !== "object" || value === null) return value;
  return Object.fromEntries(
    Object.entries(value)
      .filter(([key]) => key !== "version" && !(newIssue && key === "number"))
      .map(([key, item]) => [
        key,
        timestamps.includes(key) && typeof item === "string"
          ? "<server-clock-present>"
          : comparable(item, [], false),
      ]),
  );
}

export function predictionView(view: Snapshot, before: Snapshot): object {
  return Object.fromEntries(
    [...view]
      .filter(([entity]) => entity !== "activity")
      .map(([entity, rows]) => {
        const timestamps =
          Object.entries(EXCLUSIONS.timestamps).find(([key]) => key === entity)?.[1] ?? [];
        return [
          entity,
          Object.fromEntries(
            [...rows]
              .filter(([id]) => entity !== "notifications" || before.get(entity)?.has(id))
              .sort(([a], [b]) => a.localeCompare(b))
              .map(([id, row]) => [
                id,
                comparable(row, timestamps, entity === "issues" && !before.get(entity)?.has(id)),
              ]),
          ),
        ];
      }),
  );
}

export function exactView(view: Snapshot): object {
  return Object.fromEntries(
    [...view].map(([entity, rows]) => [
      entity,
      Object.fromEntries([...rows].sort(([a], [b]) => a.localeCompare(b))),
    ]),
  );
}
